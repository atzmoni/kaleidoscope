#!/usr/bin/env python3
"""Builds the language files for assets/i18n.js.

tools/i18n/translations.tsv is the source of truth: one row per Hebrew UI string (column "he"),
then en, zh, hi, es, ar. This script writes assets/i18n/<lang>.js from it and lists Hebrew strings
in the apps that have no row yet, so new UI text can be added to the table.

  python3 tools/i18n-build.py            # write the language files, list missing strings
  python3 tools/i18n-build.py --missing  # only list missing strings, as rows ready to fill in

The tokenizer below must match RUN in assets/i18n.js: a "string" is a run of Hebrew words joined by
spaces, punctuation or gershayim. Numbers, Latin words and markup split runs.
"""
import json, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SOURCES = ["src/builder.src.html", "kaleidoscope-studio.html", "kaleidoscope-phone.html",
           "assets/studio-phone.js", "src/studio-pro.js", "src/selfie-show.js"]
LANGS = ["en", "zh", "hi", "es", "ar"]
H = r"[֐-׿יִ-ﭏ]"
RUN = re.compile(H + r"+(?:(?:['\"׳״]|[ \t\r\n\-–—,.:;!?/…]+)" + H + r"+)*(?:['\"׳״](?!\w))?")


def keys_in(path):
    s = open(path, encoding="utf-8").read()
    s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
    out = []
    for m in RUN.finditer(s):
        k = re.sub(r"\s+", " ", m.group(0)).strip()
        k = re.sub(r"['\"]$", "", k)
        if re.search(r"[א-ת]", k):
            out.append(k)
    return out


def main():
    os.chdir(ROOT)
    rows = [l.rstrip("\n").split("\t") for l in open("tools/i18n/translations.tsv", encoding="utf-8")]
    head, rows = rows[0], rows[1:]
    table = {r[0]: r for r in rows}
    missing = []
    for f in SOURCES:
        if not os.path.exists(f):
            continue
        for k in keys_in(f):
            if k not in table and k not in missing:
                missing.append(k)
    if "--missing" not in sys.argv:
        os.makedirs("assets/i18n", exist_ok=True)
        for lang in LANGS:
            col = head.index(lang)
            d = {r[0]: r[col] for r in rows if len(r) > col and r[col] != ""}
            body = json.dumps(d, ensure_ascii=False, separators=(",", ":"))
            with open(f"assets/i18n/{lang}.js", "w", encoding="utf-8") as fh:
                fh.write("/* Generated by tools/i18n-build.py from tools/i18n/translations.tsv. Do not edit. */\n")
                fh.write("KI18N.load(" + body + ");\n")
        print(f"wrote assets/i18n/{{{','.join(LANGS)}}}.js, {len(rows)} strings")
    if missing:
        print(f"{len(missing)} Hebrew strings have no translation yet (they show in Hebrew):")
        for k in missing:
            print(k + "\t" * len(LANGS))
    else:
        print("every Hebrew string in the apps has a translation")


if __name__ == "__main__":
    main()
